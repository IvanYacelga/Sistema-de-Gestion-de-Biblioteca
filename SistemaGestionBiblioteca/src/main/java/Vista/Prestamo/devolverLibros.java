    public void mostrarResultadosPrestamos(List<Prestamo> lista) {
        String[] columnas = {"ID Prestamo", "Cedula Cliente", "ISBN Libro", "Estado", "Fecha Prestamo", "Fecha Limite", "Cedula Admin"};
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0);
        for (Prestamo p : lista) {
            modelo.addRow(new Object[]{
                p.getId(),
                p.getCedulaUsuario(),
                p.getIsbnLibro(),
                p.getEstado(),
                p.getFechaPrestamo(),
                p.getFechaLimiteDevolucion(),
                p.getCedulaAdministrador()
            });
        }
        tablaPrestamos.setModel(modelo);
    }

    public void cargarTablaPrestamos() {
        mostrarResultadosPrestamos(conexion.leerDatosPrestamos());
    }

    private void fechaDevolucionPropertyChange(java.beans.PropertyChangeEvent evt) {
        if (fechaDevolucion.getDate() == null) {
            return;
        }

        // Verificar que haya una fila seleccionada
        int filaSeleccionada = tablaPrestamos.getSelectedRow();
        if (filaSeleccionada == -1) {
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) tablaPrestamos.getModel();

        // Obtener fecha limite de la fila seleccionada (columna 5)
        Object fechaLimiteObj = modelo.getValueAt(filaSeleccionada, 5);
        LocalDate fechaLimite = LocalDate.parse(String.valueOf(fechaLimiteObj));

        // Fecha de devolucion seleccionada
        LocalDate fechaDevolucionReal = fechaDevolucion.getDate().toInstant()
                .atZone(java.time.ZoneId.systemDefault()).toLocalDate();

        // Calcular dias de retraso
        long dias = java.time.temporal.ChronoUnit.DAYS.between(fechaLimite, fechaDevolucionReal);

        if (dias > 0) {
            // Hay retraso
            double tarifaPorDia = 0.50; // $0.50 por dia
            double multa = dias * tarifaPorDia;

            diasRetraso.setText(String.valueOf(dias));
            multaGenerada.setText(String.format("$%.2f", multa));
        } else {
            // Sin retraso
            diasRetraso.setText("0");
            multaGenerada.setText("$0.00");
        }
    }


