    private void registroDevolucionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_registroDevolucionActionPerformed

       int filaSeleccionada = tablaPrestamos.getSelectedRow();
    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un prestamo de la tabla");
        return;
    }

    if (fechaDevolucion.getDate() == null) {
        JOptionPane.showMessageDialog(this, "Seleccione la fecha de devolucion");
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) tablaPrestamos.getModel();

    String idPrestamo    = String.valueOf(modelo.getValueAt(filaSeleccionada, 0));
    String cedula        = String.valueOf(modelo.getValueAt(filaSeleccionada, 1));
    String isbn          = String.valueOf(modelo.getValueAt(filaSeleccionada, 2));
    Object fechaLimiteObj = modelo.getValueAt(filaSeleccionada, 5);
    LocalDate fechaLimite = LocalDate.parse(String.valueOf(fechaLimiteObj));

    LocalDate fechaDevolucionReal = fechaDevolucion.getDate().toInstant()
            .atZone(java.time.ZoneId.systemDefault()).toLocalDate();

    boolean resultado = conexion.registrarDevolucion(
            idPrestamo,
            cedula,
            isbn,
            fechaDevolucionReal,
            fechaLimite,
            String.valueOf(activo.getCedula())
    );

    if (resultado) {
        long dias = java.time.temporal.ChronoUnit.DAYS.between(fechaLimite, fechaDevolucionReal);
        if (dias > 0) {
            JOptionPane.showMessageDialog(this, "Devolucion registrada con " + dias + " dias de retraso.\nMulta generada: " + multaGenerada.getText());
            new FrmGestionPrestamos(activo).setVisible(true); 
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Devolucion registrada correctamente sin retraso");
            new FrmGestionPrestamos(activo).setVisible(true); 
            this.dispose();
        }
        cargarTablaPrestamos();
        diasRetraso.setText("0");
        multaGenerada.setText("$0.00");
        fechaDevolucion.setDate(null);
    } else {
        JOptionPane.showMessageDialog(this, "Error al registrar devolucion");
    }
    }//GEN-LAST:event_registroDevolucionActionPerformed

